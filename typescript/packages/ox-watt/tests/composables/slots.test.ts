import { mount } from '@vue/test-utils';
import {
    defineComponent,
    h,
    type PropType,
} from 'vue';
import { describe, expect, it, vi } from 'vitest';

import { mapSlots } from '@/composables/slots';

/**
 * Item used by the test components.
 */
interface TestItem {
    id: number;
    title: string;
}

/**
 * Creates a target component used to test slot forwarding.
 *
 * @returns A component exposing title and actions slots.
 */
function createTargetComponent() {
    return defineComponent({
        name: 'TargetComponent',

        props: {
            item: {
                type: Object as PropType<TestItem>,
                required: true,
            },
        },

        emits: ['select'],

        setup(props, { emit, slots }) {
            return () => h('div', { class: 'target' }, [
                h('div', { class: 'title' }, slots.title?.({
                    item: props.item,
                })),

                h('div', { class: 'actions' }, slots.actions?.({
                    item: props.item,
                })),

                h('button', {
                    class: 'select',
                    onClick: () => emit('select', props.item),
                }, 'Select'),
            ]);
        },
    });
}

/**
 * Creates a parent component exposing the specified slots
 * and rendering the supplied wrapper component.
 *
 * @param wrapper - Wrapper component generated by mapSlots.
 * @param slots - Slots exposed by the parent.
 * @param item - Item passed to the wrapper.
 * @param onSelect - Optional event listener.
 * @returns A mounted Vue component.
 */
function mountWrapper(
    wrapper: ReturnType<typeof mapSlots>,
    slots: Record<string, (...args: any[]) => any>,
    item: TestItem = { id: 1, title: 'Test item' },
    onSelect?: (item: TestItem) => void,
) {
    const Parent = defineComponent({
        setup() {
            return () => h(wrapper, {
                item,
                onSelect,
            }, slots);
        },
    });

    return mount(Parent);
}

describe('mapSlots', () => {
    const TargetComponent = createTargetComponent();

    describe('slot forwarding', () => {
        it('should forward all slots when no filter is specified', () => {
            const wrapperComponent = mapSlots(TargetComponent);

            const wrapper = mountWrapper(wrapperComponent, {
                title: () => h('strong', 'Item title'),
                actions: () => h('button', 'Edit'),
                other: () => h('span', 'Other slot'),
            });

            expect(wrapper.find('.title').text()).toBe('Item title');
            expect(wrapper.find('.actions').text()).toBe('Edit');
        });

        it('should preserve scoped slot arguments', () => {
            const item = { id: 42, title: 'Scoped item' };

            const wrapperComponent = mapSlots(TargetComponent);

            const wrapper = mountWrapper(wrapperComponent, {
                title: ({ item }: { item: TestItem }) => h(
                    'strong',
                    `${item.id}: ${item.title}`,
                ),
            }, item);

            expect(wrapper.find('.title').text()).toBe('42: Scoped item');
        });
    });

    describe('slot mapping', () => {
        it('should remove the configured prefix from slot names', () => {
            const wrapperComponent = mapSlots(TargetComponent, {
                prefix: 'item.',
            });

            const wrapper = mountWrapper(wrapperComponent, {
                'item.title': () => h('strong', 'Item title'),
                'item.actions': () => h('button', 'Edit'),
                other: () => h('span', 'Other'),
            });

            expect(wrapper.find('.title').text()).toBe('Item title');
            expect(wrapper.find('.actions').text()).toBe('Edit');
            expect(wrapper.text()).not.toContain('Other');
        });
    });

    describe('attribute forwarding', () => {
        it('should forward component props', () => {
            const wrapperComponent = mapSlots(
                TargetComponent,
                [],
            );

            const item = { id: 42, title: 'Forwarded item' };
            const wrapper = mountWrapper(wrapperComponent, {}, item);

            expect(wrapper.find('.target').exists()).toBe(true);
        });

        it('should forward event listeners', async () => {
            const onSelect = vi.fn();

            const wrapperComponent = mapSlots(
                TargetComponent,
                [],
            );

            const item = { id: 42, title: 'Selected item' };

            const wrapper = mountWrapper(
                wrapperComponent,
                {},
                item,
                onSelect,
            );

            await wrapper.find('.select').trigger('click');

            expect(onSelect).toHaveBeenCalledOnce();
            expect(onSelect).toHaveBeenCalledWith(item);
        });
    });

    describe('slot filtering', () => {
        it('should filter slots using a custom function', () => {
            const wrapperComponent = mapSlots(TargetComponent, {
                filter: (name) => name.startsWith('item.'),
                map: (name) => name.slice(5),
            });

            const wrapper = mountWrapper(wrapperComponent, {
                'item.title': () => h('strong', 'Item title'),
                'item.actions': () => h('button', 'Edit'),
                other: () => h('span', 'Other'),
            });

            expect(wrapper.find('.title').text()).toBe('Item title');
            expect(wrapper.find('.actions').text()).toBe('Edit');
            expect(wrapper.text()).not.toContain('Other');
        });

        it('should use the custom mapper to rename slots', () => {
            const wrapperComponent = mapSlots(TargetComponent, {
                filter: (name) => name.startsWith('custom.'),
                map: (name) => name.replace('custom.', ''),
            });

            const wrapper = mountWrapper(wrapperComponent, {
                'custom.title': () => h('strong', 'Mapped title'),
            });

            expect(wrapper.find('.title').text()).toBe('Mapped title');
        });

        it('should support prefix filtering without a custom mapper', () => {
            const wrapperComponent = mapSlots(TargetComponent, {
                prefix: 'item.',
            });

            const wrapper = mountWrapper(wrapperComponent, {
                'item.title': () => h('strong', 'Item title'),
                other: () => h('span', 'Other'),
            });

            expect(wrapper.find('.title').text()).toBe('Item title');
            expect(wrapper.text()).not.toContain('Other');
        });
    });
});
